WHITE = (255, 255, 255, 255)
CLEAR = (0, 0, 0, 0)

COLORS = {
    'JPG': (0xE0, 0x77, 0x1B, 255),
    'PNG': (0x2E, 0x9E, 0x4F, 255),
    'GIF': (0x8A, 0x3F, 0xD1, 255),
    'WEB': (0x2B, 0x6F, 0xD6, 255),
    'MP4': (0xD1, 0x45, 0x45, 255),
    'MKV': (0x3B, 0x5B, 0xDB, 255),
    'PDF': (0xB3, 0x2D, 0x2D, 255),
}

# size: card, corner, holes (x_left, x_right, w, h, ys), font/scale/spacing
PIXEL = {
    16: dict(card=(1, 1, 14, 14), corner=[1],
             holes=(2, 13, 1, 2, [3, 6, 9]), font=('3', 1, 0)),
    24: dict(card=(1, 1, 22, 22), corner=[1],
             holes=(2, 20, 2, 2, [4, 8, 12, 16]), font=('4', 1, 1)),
    32: dict(card=(1, 1, 30, 30), corner=[2, 1],
             holes=(3, 27, 2, 2, [4, 9, 14, 19, 24]), font=('5', 1, 1)),
}
FONTS = {'3': F3, '4': F4, '5': F5}
WIDTHS = {'3': 3, '4': 4, '5': 5}
HEIGHTS = {'3': 5, '4': 6, '5': 7}


def render(size, code):
    L = PIXEL[size]
    im = Image.new('RGBA', (size, size), CLEAR)
    d = ImageDraw.Draw(im)
    x0, y0, x1, y1 = L['card']
    ins = []
    for y in range(y0, y1 + 1):
        off = min(y - y0, y1 - y)
        ins.append(L['corner'][off] if off < len(L['corner']) else 0)
    for i, s in enumerate(ins):
        d.rectangle([x0 + s, y0 + i, x1 - s, y0 + i], fill=COLORS[code])
    hxl, hxr, hw, hh, ys = L['holes']
    for hy in ys:
        for hx in (hxl, hxr):
            d.rectangle([hx, hy, hx + hw - 1, hy + hh - 1], fill=WHITE)
    font, scale, spacing = L['font']
    gw, gh = WIDTHS[font], HEIGHTS[font]
    tw = (len(code) * gw + (len(code) - 1) * spacing) * scale
    th = gh * scale
    tx = (x0 + x1 + 1 - tw) // 2
    ty = (y0 + y1 + 1 - th) // 2
    cx = tx
    for ch in code:
        for r, bits in enumerate(FONTS[font][ch]):
            for c, bit in enumerate(bits):
                if bit == '1':
                    d.rectangle([cx + c * scale, ty + r * scale,
                                 cx + c * scale + scale - 1, ty + r * scale + scale - 1], fill=WHITE)
        cx += (gw + spacing) * scale
    return im


if __name__ == '__main__':
    for size in PIXEL:
        for code in ('JPG', 'PNG', 'MP4', 'MKV', 'WEB'):
            render(size, code).save(os.path.join(OUT, f'r3-{size}-{code}.png'))
    print('ok')
